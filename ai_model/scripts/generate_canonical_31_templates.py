output_json = "frontend/assets/ml/character_templates.json"
templates_dict = {}
labels = list(canonical_strokes_bank.keys())

for l in labels:
    proto_list = canonical_strokes_bank[l]
    proto_raws = []
    for proto_strokes in proto_list:
        raw_t = preprocess_strokes_to_image(proto_strokes, canvas_size=(350, 350), target_size=(32, 32))
        proto_raws.append(raw_t.round(3).tolist())
        
    first_raw = np.array(proto_raws[0], dtype=np.float32)
    blurred = gaussian_filter(first_raw, sigma=1.0)
    norm_b = np.linalg.norm(blurred)
    if norm_b > 0:
        blurred = blurred / norm_b
        
    templates_dict[l] = {
        "raw": proto_raws[0],
        "prototypes": proto_raws,
        "field": blurred.round(3).tolist()
    }

with open(output_json, "w", encoding="utf-8") as f:
    json.dump({"labels": labels, "templates": templates_dict}, f, ensure_ascii=False, indent=2)

print(f"Generated multi-prototype canonical bank for all {len(labels)} Tamil letters in {output_json}")
